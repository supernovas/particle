#!/usr/bin/env node
// Regenerate packages/ui/src/demo/history.ts from the real repo: every issue,
// PR, and merge, in order. Public API; set GITHUB_TOKEN to raise rate limits.
import { writeFileSync } from 'node:fs';

const REPO = process.argv[2] ?? 'supernovas/particle';
const headers = {
  accept: 'application/vnd.github+json',
  'user-agent': 'particle-demo-history',
  ...(process.env.GITHUB_TOKEN ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
};

async function pages(path) {
  const all = [];
  for (let page = 1; page <= 5; page++) {
    const res = await fetch(`https://api.github.com${path}&per_page=100&page=${page}`, { headers });
    if (!res.ok) throw new Error(`${path}: ${res.status}`);
    const batch = await res.json();
    all.push(...batch);
    if (batch.length < 100) break;
  }
  return all;
}

const snippet = (text, n = 110) => {
  const flat = (text ?? '').replace(/\s+/g, ' ').trim();
  return flat.length > n ? `${flat.slice(0, n - 1)}…` : flat;
};

const items = await pages(`/repos/${REPO}/issues?state=all&sort=created&direction=asc`);
const events = [];
const avatars = {};
const face = (user) => {
  if (user?.login && !avatars[user.login]) avatars[user.login] = user.avatar_url;
};
for (const item of items) {
  const isPr = Boolean(item.pull_request);
  face(item.user);
  events.push({
    at: item.created_at,
    kind: isPr ? 'pr' : 'issue',
    number: item.number,
    title: item.title,
    author: item.user.login,
    body: isPr ? '' : snippet(item.body),
  });
  if (isPr && item.pull_request.merged_at) {
    events.push({
      at: item.pull_request.merged_at,
      kind: 'merge',
      number: item.number,
      title: item.title,
      author: item.user.login,
      body: '',
    });
  }
}
const comments = await pages(`/repos/${REPO}/issues/comments?sort=created&direction=asc`);
for (const comment of comments) {
  const number = Number(comment.issue_url.split('/').pop());
  face(comment.user);
  events.push({
    at: comment.created_at,
    kind: 'comment',
    number,
    title: '',
    author: comment.user.login,
    body: snippet(comment.body),
  });
}
events.sort((a, b) => a.at.localeCompare(b.at) || a.number - b.number);

const lines = events
  .map(
    (e) =>
      `  { at: '${e.at}', kind: '${e.kind}', number: ${e.number}, title: ${JSON.stringify(e.title)}, author: ${JSON.stringify(e.author)}, body: ${JSON.stringify(e.body ?? '')} },`,
  )
  .join('\n');
writeFileSync(
  'packages/ui/src/demo/history.ts',
  `// Generated by scripts/gen-demo-history.mjs — every issue, PR, and merge in ${REPO}.
export interface RepoEvent {
  at: string;
  kind: 'issue' | 'pr' | 'merge' | 'comment';
  number: number;
  title: string;
  author: string;
  body: string;
}

export const HISTORY: RepoEvent[] = [
${lines}
];

export const AVATARS: Record<string, string> = ${JSON.stringify(avatars, null, 2).replace(/"([^"]+)":/g, "'$1':").replace(/"/g, "'")};
`,
);
console.log(`wrote ${events.length} events`);
